import importlib as _testtailor_importlib
import unittest
from unittest.mock import AsyncMock, MagicMock, Mock, PropertyMock, call, patch

try:
    _testtailor_target = _testtailor_importlib.import_module('openhands.core.config.mcp_config')
except Exception:
    _testtailor_target = None
else:
    globals().update({
        name: value
        for name, value in vars(_testtailor_target).items()
        if not name.startswith("__")
    })

class _TestTailorTimeout:
    @staticmethod
    def timeout(_seconds):
        return lambda function: function

timeout_decorator = _TestTailorTimeout()

class Test(unittest.TestCase):
    @timeout_decorator.timeout(1)
    def test_case_XX(self):
        """URL with a scheme but no domain/host should raise the expected ValueError."""
        with self.assertRaises(ValueError) as cm:
            # URL includes a scheme but has no netloc/domain
            _validate_mcp_url('http://')
        self.assertEqual(str(cm.exception), 'URL must include a valid domain/host')
