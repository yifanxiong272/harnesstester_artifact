def test_returns_cached_user_description_round_043():
    provider = DummyGitProvider()
    # set cached value; get_pr_description_full MUST NOT be called
    provider.user_description = "cached description"

    def _fail_if_called(self):
        raise AssertionError("get_pr_description_full should not be called when user_description exists")

    provider.get_pr_description_full = types.MethodType(lambda self: _fail_if_called(self), provider)

    result = provider.get_user_description()
    assert result == "cached description"
    # Ensure cached value preserved
    assert provider.user_description == "cached description"


def test_not_generated_returns_existing_description_round_043():
    provider = DummyGitProvider()

    desc = "This is a manually written description by user."

    provider.get_pr_description_full = types.MethodType(lambda self: desc, provider)
    # Simulate detection that it was NOT generated by pr-agent
    provider._is_generated_by_pr_agent = types.MethodType(lambda self, d: False, provider)

    result = provider.get_user_description()
    assert result == desc
    # Should cache the user description as-is
    assert getattr(provider, "user_description") == desc


def test_generated_without_user_section_returns_empty_round_043():
    provider = DummyGitProvider()

    # a pr-agent generated description but missing the user description header
    generated = "### **generated by pr-agent**\nNo user section here"
    provider.get_pr_description_full = types.MethodType(lambda self: generated, provider)
    provider._is_generated_by_pr_agent = types.MethodType(lambda self, d: True, provider)

    result = provider.get_user_description()
    assert result == ""  # should return empty string when generated but no user section
    # Should not set a non-empty user_description attribute
    assert not hasattr(provider, "user_description") or provider.user_description in (None, "")


def test_extraction_between_headers_trims_trailing_underscores_round_043():
    provider = DummyGitProvider()

    # Compose a description where user description is between user header and another header
    # and ends with trailing underscores '___' that should be removed
    user_header = "### **user description**"
    other_header = "### **changes**"
    description = (
        f"Intro text\n{user_header}\nMy original user text ___\n{other_header}\nRemaining"
    )

    provider.get_pr_description_full = types.MethodType(lambda self: description, provider)
    provider._is_generated_by_pr_agent = types.MethodType(lambda self, d: True, provider)
    # _possible_headers should return the same header strings that will be searched in lowercase
    provider._possible_headers = types.MethodType(lambda self: [user_header, other_header], provider)

    result = provider.get_user_description()
    assert result == "My original user text"
    # Should be cached on the instance
    assert provider.user_description == "My original user text"


def test_extraction_no_other_header_strips_header_before_marker_round_043():
    provider = DummyGitProvider()

    user_header = "### **user description**"
    # No other header present; the description contains the header and then content followed by marker ___
    description = f"{user_header}\nActual content ___"

    provider.get_pr_description_full = types.MethodType(lambda self: description, provider)
    provider._is_generated_by_pr_agent = types.MethodType(lambda self, d: True, provider)
    # Only include the user header in possible headers
    provider._possible_headers = types.MethodType(lambda self: [user_header], provider)

    result = provider.get_user_description()
    assert result == "Actual content"
    assert provider.user_description == "Actual content"
