def test_cached_user_description_is_returned_without_calling_description_method():
    p = DummyProvider(pr_description="should not be used")
    # set cached user_description to ensure early return
    p.user_description = "cached-desc"
    result = p.get_user_description()
    assert result == "cached-desc"
    # ensure cached attribute remains unchanged
    assert p.user_description == "cached-desc"


def test_non_generated_description_sets_user_description_and_returns_it():
    desc = "A user provided description that was not generated by the pr-agent."
    p = DummyProvider(pr_description=desc)
    p._generated = False  # simulate not generated by pr-agent
    # ensure no prior user_description
    assert not hasattr(p, "user_description")
    result = p.get_user_description()
    assert result == desc
    # attribute should be set to the same description
    assert p.user_description == desc


def test_generated_but_no_user_header_returns_empty_string():
    # description is considered generated but doesn't contain the user header
    desc = "this description was generated by pr-agent but has no user header"
    p = DummyProvider(pr_description=desc)
    p._generated = True
    # ensure header string not present in description_lowercase
    assert "### **user description**" not in desc.lower()
    result = p.get_user_description()
    assert result == ""
    # user_description attribute should not be set in this branch
    assert not hasattr(p, "user_description")


def test_generated_with_header_and_following_header_truncates_and_strips_trailing_underscores():
    # Build a description where user description ends with '___' and followed by another header
    user_text = "This is the original user description that should be extracted ___"
    # Put headers exactly as expected (case-insensitive handling uses lower())
    description = "### **user description**\n" + user_text + "\n### next header\nSome other generated content"
    p = DummyProvider(pr_description=description)
    p._generated = True
    # possible headers include the next header so the parsing loop will find it and set end_position
    p._possible = ["### **user description**", "### next header"]
    result = p.get_user_description()
    # trailing '___' should be removed and whitespace trimmed
    assert result == "This is the original user description that should be extracted"
    # and provider should cache it
    assert p.user_description == result


def test_generated_with_header_and_no_following_header_uses_split_logic_and_header_stripped():
    # Build a description that starts with the user header and uses '___' to indicate separation,
    # but has no other headers that would be found by possible_headers (so end_position == len(description))
    user_text = "User's multi-line description\nwith more details"
    # include separator ___ later so split("___") works
    description = "### **user description**\n" + user_text + "___\nSome trailing generated content"
    p = DummyProvider(pr_description=description)
    p._generated = True
    # possible headers contains only the user header so no other header will be found
    p._possible = ["### **user description**"]
    result = p.get_user_description()
    # The logic should remove the header and return the portion before '___', trimmed
    expected = user_text.strip()
    assert result == expected
    assert p.user_description == expected
